class Plant {
  final String id;
  final String name;
  final String imageUrl;
  final String height;
  final String plantType;
  final double rating;
  final double price;
  final String description;

  const Plant({
    required this.id,
    required this.name,
    required this.imageUrl,
    required this.height,
    required this.plantType,
    required this.rating,
    required this.price,
    required this.description,
  });
}
